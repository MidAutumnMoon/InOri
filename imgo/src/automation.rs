    #[test]
    fn reviewed_artifact_requires_exact_source_and_recipe()
    -> rootcause::Result<()> {
        let directory = tempfile::tempdir()?;
        let review = directory.path().join(REVIEW_DIR_NAME);
        let artifact_relative =
            PathBuf::from("001--group--page/01-selected--safe.avif");
        let artifact = review.join(&artifact_relative);
        std::fs::create_dir_all(
            artifact.parent().context("artifact parent")?,
        )?;
        std::fs::write(&artifact, b"encoded")?;
        let source_path = directory.path().join("page.png");
        std::fs::write(&source_path, b"source")?;
        let planned = PlannedFile::from_path(
            PathBuf::from("page.png"),
            &source_path,
        )?;
        let recipe = Recipe::single(Step::Avif(Avif::default()));
        let metadata = std::fs::metadata(&artifact)?;
        let modified = metadata.modified()?.duration_since(UNIX_EPOCH)?;
        let manifest = ReviewManifest {
            version: REVIEW_VERSION,
            workspace: directory.path().to_path_buf(),
            candidates: vec![ReviewedCandidate {
                source: planned.clone(),
                recipe_name: "safe".to_owned(),
                recipe: recipe.clone(),
                artifact: artifact_relative,
                output_extension: "avif".to_owned(),
                encoded_modified_unix_seconds: modified.as_secs(),
                encoded_modified_subsec_nanos: modified.subsec_nanos(),
                encoded_bytes: metadata.len(),
            }],
        };

        assert!(
            reviewed_candidate(
                &manifest,
                &review,
                &planned,
                ImageFormat::PNG,
                "safe",
                &recipe,
            )?
            .is_some()
        );
        let changed_recipe = Recipe::single(Step::Avif(Avif {
            quality: 64,
            ..Avif::default()
        }));
        assert!(
            reviewed_candidate(
                &manifest,
                &review,
                &planned,
                ImageFormat::PNG,
                "safe",
                &changed_recipe,
            )?
            .is_none()
        );
        let mut changed_source = planned;
        changed_source.bytes += 1;
        assert!(
            reviewed_candidate(
                &manifest,
                &review,
                &changed_source,
                ImageFormat::PNG,
                "safe",
                &recipe,
            )?
            .is_none()
        );
        Ok(())
    }

