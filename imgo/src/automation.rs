#[derive(Debug)]
pub struct PlanOpts {
    /// Directory containing source PNG/JPEG images.
    pub workspace: PathBuf,

    /// JSON plan path. Defaults to `<workspace>/imgo-plan.json`.
    pub output: Option<PathBuf>,

    /// Review directory. Defaults to `<workspace>/.imgo-review`.
    pub review_output: Option<PathBuf>,

    /// Analyze only immediate children of the workspace.
    pub no_recursive: bool,

    /// Number of images decoded concurrently (default: at most four).
    pub jobs: Option<NonZeroU64>,

    /// Replace an existing plan and force fresh candidate encodes.
    pub force: bool,
}

/// CLI parser for [`PlanOpts`].
#[must_use]
pub fn plan_cli() -> impl Parser<PlanOpts> {
    let output = long("output")
        .short('o')
        .argument::<PathBuf>("PATH")
        .help("JSON plan path. Defaults to `<workspace>/imgo-plan.json`")
        .optional();
    let review_output = long("review-output")
        .argument::<PathBuf>("DIR")
        .help("Review directory. Defaults to `<workspace>/.imgo-review`")
        .optional();
    let no_recursive = long("no-recursive")
        .short('R')
        .switch()
        .help("Analyze only immediate children of the workspace");
    let jobs = long("jobs")
        .short('J')
        .argument::<NonZeroU64>("N")
        .help("Number of images decoded concurrently (default: at most four)")
        .optional();
    let force = long("force").switch().help(
        "Replace an existing plan and force fresh candidate encodes",
    );
    let workspace = positional::<PathBuf>("WORKSPACE")
        .help("Directory containing source PNG/JPEG images")
        .fallback(PathBuf::from("."));
    construct!(PlanOpts {
        output,
        review_output,
        no_recursive,
        jobs,
        force,
        workspace,
    })
}

#[derive(Debug)]
pub struct RunOpts {
    /// Reviewed plan generated by `i plan`.
    pub plan: PathBuf,

    /// Number of images processed concurrently. Defaults to one because
    /// avifenc/cjxl use all cores internally.
    pub jobs: Option<NonZeroU64>,

    /// Keep originals in place. The default moves them into `.backup` and
    /// enables reliable resume detection.
    pub no_backup: bool,
}

/// CLI parser for [`RunOpts`].
#[must_use]
pub fn run_cli() -> impl Parser<RunOpts> {
    let jobs = long("jobs")
        .short('J')
        .argument::<NonZeroU64>("N")
        .help(
            "Number of images processed concurrently. Defaults to one \
             because avifenc/cjxl use all cores internally",
        )
        .optional();
    let no_backup = long("no-backup").short('N').switch().help(
        "Keep originals in place. The default moves them into \
             `.backup` and enables reliable resume detection",
    );
    let plan = positional::<PathBuf>("PLAN")
        .help("Reviewed plan generated by `i plan`");
    construct!(RunOpts {
        jobs,
        no_backup,
        plan,
    })
}

